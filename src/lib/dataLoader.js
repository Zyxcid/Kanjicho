import n5 from "../data/n5.json";
import n4 from "../data/n4.json";
import n3 from "../data/n3.json";
import n2 from "../data/n2.json";
import n1 from "../data/n1.json";
import n5Examples from "../data/n5_examples.json";
import n4Examples from "../data/n4_examples.json";
import n3Examples from "../data/n3_examples.json";
import n2Examples from "../data/n2_examples.json";
import n1Examples from "../data/n1_examples.json";

const RAW_LEVELS = { N5: n5, N4: n4, N3: n3, N2: n2, N1: n1 };
const EXAMPLES = { N5: n5Examples, N4: n4Examples, N3: n3Examples, N2: n2Examples, N1: n1Examples };

/* ============================================================
   Kana → Romaji converter
   ------------------------------------------------------------
   Used to derive a corrected `primary_romaji` set from the raw
   KANJIDIC2 readings (readings.on / readings.kun), which are stored
   as kana. The pre-existing `primary_romaji` field in the JSON is
   unreliable — it often drops the kun'yomi (e.g. 言 has primary
   ["gen","gon"] but no "iu") and was generated by a lossy external
   pipeline. We re-derive it at load time instead.

   Handles:
     - katakana ↔ hiragana (convert to hiragana first)
     - long vowel mark ー (extends the vowel of the previous kana)
     - small ゃゅょぁぃぅぇぉ (palatalization, e.g. しゃ→sha, じ→ji)
     - the っ/ッ gemination (doubled consonant, e.g. まっ→ma→mat-ta)
     - the "." separator in kun'yomi (e.g. い.う → "iu", だ.す → "dasu")
     - leading "-" in kun'yomi (prefix okurigana, e.g. "-だ.す" → "dasu")
   ============================================================ */

// Full hiragana → romaji table for basic + palatal + small kana.
// Long-vowel ー and gemination っ are handled separately below.
const KANA_TO_ROMAJI = {
  // a
  あ: "a", い: "i", う: "u", え: "e", お: "o",
  // k
  か: "ka", き: "ki", く: "ku", け: "ke", こ: "ko",
  // s
  さ: "sa", し: "shi", す: "su", せ: "se", そ: "so",
  // t
  た: "ta", ち: "chi", つ: "tsu", て: "te", と: "to",
  // n
  な: "na", に: "ni", ぬ: "nu", ね: "ne", の: "no",
  // h
  は: "ha", ひ: "hi", ふ: "fu", へ: "he", ほ: "ho",
  // m
  ま: "ma", み: "mi", む: "mu", め: "me", も: "mo",
  // y
  や: "ya", ゆ: "yu", よ: "yo",
  // r
  ら: "ra", り: "ri", る: "ru", れ: "re", ろ: "ro",
  // w
  わ: "wa", を: "wo",
  // n (single)
  ん: "n",
  // g
  が: "ga", ぎ: "gi", ぐ: "gu", げ: "ge", ご: "go",
  // z
  ざ: "za", じ: "ji", ず: "zu", ぜ: "ze", ぞ: "zo",
  // d
  だ: "da", ぢ: "ji", づ: "zu", で: "de", ど: "do",
  // b
  ば: "ba", び: "bi", ぶ: "bu", べ: "be", ぼ: "bo",
  // p
  ぱ: "pa", ぴ: "pi", ぷ: "pu", ぺ: "pe", ぽ: "po",
  // small vowels ( standalone rare; usually palatal handled below )
  ぁ: "a", ぃ: "i", ぅ: "u", ぇ: "e", ぉ: "o",
  // small y (handled as palatal combos but keep standalone fallback)
  ゃ: "ya", ゅ: "yu", ょ: "yo",
  // small tsu (gemination handled separately)
  っ: "",
};

// Palatal combination table: <base><small-y> → single syllable.
// e.g. き+ゃ → "kya", し+ゅ → "shu", じ+ょ → "jo"
const PALATAL = {
  ki: { ya: "kya", yu: "kyu", yo: "kyo" },
  gi: { ya: "gya", yu: "gyu", yo: "gyo" },
  shi: { ya: "sha", yu: "shu", yo: "sho" },
  ji: { ya: "ja", yu: "ju", yo: "jo" },
  chi: { ya: "cha", yu: "chu", yo: "cho" },
  // ぢ ji
  ni: { ya: "nya", yu: "nyu", yo: "nyo" },
  hi: { ya: "hya", yu: "hyu", yo: "hyo" },
  bi: { ya: "bya", yu: "byu", yo: "byo" },
  pi: { ya: "pya", yu: "pyu", yo: "pyo" },
  mi: { ya: "mya", yu: "myu", yo: "myo" },
  ri: { ya: "rya", yu: "ryu", yo: "ryo" },
};

// Vowel-extension table for the long vowel mark ー (e.g. すー → "suu", こー → "kou").
const LONG_VOWEL = {
  a: "a", i: "i", u: "u", e: "e", o: "o",
  // palatal bases extend their last vowel
  sha: "a", shu: "u", sho: "o",
  cha: "a", chu: "u", cho: "o",
  ja: "a", ju: "u", jo: "o",
};

function kanaToRomaji(kanaStr) {
  // Normalize katakana → hiragana, then strip the okurigana separators.
  let s = kanaStr
    .replace(/[ァ-ン]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .replace(/[ァィゥェォャュョッ]/g, (ch) => {
      // small katakana → small hiragana
      const map = { ァ: "ぁ", ィ: "ぃ", ゥ: "ぅ", ェ: "ぇ", ォ: "ぉ", ャ: "ゃ", ュ: "ゅ", ョ: "ょ", ッ: "っ" };
      return map[ch] || ch;
    })
    .replace(/\./g, "") // kun'yomi okurigana separator
    .replace(/^-/, ""); // leading "-" (prefix okurigana)

  let out = "";
  let i = 0;
  while (i < s.length) {
    const ch = s[i];
    const next = s[i + 1];

    // Gemination: small っ → double the next consonant.
    if (ch === "っ") {
      const nxt = KANA_TO_ROMAJI[next];
      if (nxt && nxt.length > 0) {
        out += nxt[0];
        i++;
        continue;
      }
      // っ at end with no following → "tsu"
      out += "tsu";
      i++;
      continue;
    }

    // Long vowel mark ー: extend the previous kana's vowel.
    if (ch === "ー") {
      // Find the last emitted "vowel" — look at the tail of `out`.
      const m = out.match(/[aeiou]+$/);
      if (m) {
        out += LONG_VOWEL[m[0].slice(-1)] || m[0].slice(-1);
      }
      i++;
      continue;
    }

    const base = KANA_TO_ROMAJI[ch];
    // Palatal combination: <i-base> + small y.
    if (next === "ゃ" || next === "ゅ" || next === "ょ") {
      const ySmall = KANA_TO_ROMAJI[next]; // ya/yu/yo
      if (base && PALATAL[base] && PALATAL[base][ySmall]) {
        out += PALATAL[base][ySmall];
        i += 2;
        continue;
      }
    }

    // Small vowel after a base: combine (e.g. てぃ → "ti", ふぁ → "fa").
    // Fallback: just append.
    if (base !== undefined) {
      out += base;
    }
    i++;
  }
  return out;
}

/**
 * Derive a corrected primary_romaji set for one kanji:
 *   { romaji(readings.on[0]), romaji(readings.kun[0]) }
 * KANJIDIC2 lists readings in roughly frequency order, so [0] is the most
 * common on'yomi / kun'yomi. Dedupes (e.g. 日 on[0]="ニチ"→"nichi",
 * kun[0]="ひ"→"hi" → ["nichi","hi"]). Drops empty/missing entries.
 */
function derivePrimaryRomaji(entry) {
  const out = [];
  const seen = new Set();
  const on0 = entry.readings?.on?.[0];
  const kun0 = entry.readings?.kun?.[0];
  for (const kana of [on0, kun0]) {
    if (!kana) continue;
    const r = kanaToRomaji(kana);
    if (r && !seen.has(r)) {
      seen.add(r);
      out.push(r);
    }
  }
  return out;
}

// Build the merged LEVELS map: each kanji gets its examples attached AND its
// `primary_romaji` re-derived at load time (overriding the unreliable value
// baked into the JSON by the external pipeline). This is done once here so
// every other module (quizGenerator, components) reads the corrected field.
const LEVELS = Object.fromEntries(
  Object.entries(RAW_LEVELS).map(([level, kanjiList]) => [
    level,
    kanjiList.map((k) => ({
      ...k,
      examples: EXAMPLES[level]?.[k.kanji] || [],
      primary_romaji: derivePrimaryRomaji(k),
    })),
  ])
);

export const LEVEL_IDS = ["N5", "N4", "N3", "N2", "N1"];

export function getKanjiForLevel(level) {
  return LEVELS[level] || [];
}

export function getUnitsForLevel(level) {
  return [...new Set(getKanjiForLevel(level).map((k) => k.unit))];
}

export function getKanjiForUnit(level, unitId) {
  return getKanjiForLevel(level).filter((k) => k.unit === unitId);
}

export function getLevelMeta(level) {
  const kanjiList = getKanjiForLevel(level);
  return { total: kanjiList.length, units: getUnitsForLevel(level).length };
}

