#!/usr/bin/env python3
"""self-host Google Fonts (menghapus request pihak ketiga).

Latar: Play Store + privacy "no data collected". Font Google via CDN
(fonts.googleapis.com) mengirim IP user ke server Google saat load pertama.
Fix: unduh SEMUA subset woff2 (unicode-range) ke public/fonts/, lalu
generate src/styles/fonts.css dengan @font-face lokal (font-display swap).

Keluarga & weight mengikuti index.html lama:
  Shippori Mincho 400/600/800 · Zen Kaku Gothic New 400/500/700/900 ·
  DM Mono 400/500 (display=swap).

Pemakaian: python scripts/fetch_fonts.py
Output: public/fonts/**, src/styles/fonts.css, ringkasan ukuran.
"""

import concurrent.futures
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS_DIR = os.path.join(ROOT, "public", "fonts")
CSS_OUT = os.path.join(ROOT, "src", "styles", "fonts.css")

CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Shippori+Mincho:wght@400;600;800&"
    "family=Zen+Kaku+Gothic+New:wght@400;500;700;900&"
    "family=DM+Mono:wght@400;500&display=swap"
)
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

SLUG = {
    "Shippori Mincho": "shippori-mincho",
    "Zen Kaku Gothic New": "zen-kaku-gothic-new",
    "DM Mono": "dm-mono",
}


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def parse_blocks(css_text):
    """Pecah CSS Google menjadi dict per @font-face."""
    blocks = []
    for raw in css_text.split("@font-face")[1:]:
        body = raw.split("}", 1)[0]
        fam = re.search(r"font-family:\s*'([^']+)'", body)
        wgt = re.search(r"font-weight:\s*(\d+)", body)
        sty = re.search(r"font-style:\s*(\w+)", body)
        src = re.search(r"src:\s*url\(([^)]+)\)", body)
        rng = re.search(r"unicode-range:\s*([^;]+);", body)
        if not (fam and wgt and src):
            continue
        blocks.append(
            {
                "family": fam.group(1),
                "weight": wgt.group(1),
                "style": sty.group(1) if sty else "normal",
                "url": src.group(1),
                "range": rng.group(1).strip() if rng else None,
            }
        )
    return blocks


def main():
    print(f"Fetch CSS: {CSS_URL}")
    css = fetch(CSS_URL).decode("utf-8")
    blocks = parse_blocks(css)
    print(f"@font-face blocks ditemukan: {len(blocks)}")

    # Nama file lokal deterministik: <slug>-<weight>-<idx>.woff2
    per_fam = {}
    for i, b in enumerate(blocks):
        slug = SLUG[b["family"]]
        b["local"] = os.path.join(FONTS_DIR, f"{slug}-{b['weight']}-{i:03d}.woff2")
        per_fam.setdefault(b["family"], 0)
        per_fam[b["family"]] += 1
    for fam, n in sorted(per_fam.items()):
        print(f"  {fam}: {n} subset")

    os.makedirs(FONTS_DIR, exist_ok=True)

    def dl(b):
        if os.path.exists(b["local"]) and os.path.getsize(b["local"]) > 0:
            return b["local"], os.path.getsize(b["local"]), True
        data = fetch(b["url"])
        with open(b["local"], "wb") as f:
            f.write(data)
        return b["local"], len(data), False

    total = 0
    cached = 0
    failed = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as ex:
        for path, size, existed in ex.map(dl, blocks):
            if size == 0:
                failed.append(path)
                continue
            total += size
            cached += 1 if existed else 0

    if failed:
        print(f"GAGAL mengunduh {len(failed)} file:")
        for p in failed:
            print(f"  {p}")
        sys.exit(1)

    # Tulis fonts.css — @font-face lokal, font-display swap, unicode-range asli.
    lines = [
        "/* SELF-HOSTED — generated by scripts/fetch_fonts.py.",
        " * Google Fonts (OFL 1.1): Shippori Mincho, Zen Kaku Gothic New,",
        " * DM Mono. Subset woff2 di public/fonts/; unicode-range asli Google",
        " * dipertahankan sehingga browser hanya memuat subset yang dipakai.",
        " * TIDAK ada request ke pihak ketiga — privacy 'no data collected'.",
        " * Regenerasi: python scripts/fetch_fonts.py */",
    ]
    for b in blocks:
        rel = f"/fonts/{os.path.basename(b['local'])}"
        lines += [
            "@font-face {",
            f"  font-family: '{b['family']}';",
            f"  font-style: {b['style']};",
            f"  font-weight: {b['weight']};",
            "  font-display: swap;",
            f"  src: url('{rel}') format('woff2');",
        ]
        if b["range"]:
            lines.append(f"  unicode-range: {b['range']};")
        lines.append("}")
        lines.append("")
    with open(CSS_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"\nSelesai: {cached} file woff2 (total {total/1024/1024:.2f} MB)")
    for fam in sorted(per_fam):
        n = sum(
            os.path.getsize(b["local"])
            for b in blocks
            if b["family"] == fam
        )
        print(f"  {fam}: {n/1024/1024:.2f} MB ({per_fam[fam]} file)")
    print(f"CSS: {os.path.relpath(CSS_OUT, ROOT)} ({len(blocks)} blok)")


if __name__ == "__main__":
    main()
